/**
 * Generates `src/core/icons/builtin-assets.ts` from the manifests under
 * `icons/`.
 *
 * The compiled binary cannot read `icons/` at runtime, so every builtin SVG is
 * embedded as a string keyed by `<slug>:<key>`. The output is deterministic
 * (sorted packs/keys, JSON-escaped contents) so re-running the script on an
 * unchanged tree produces an identical file.
 *
 * Run with `bun run icons:assets`.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { ICON_KEYS, ICON_PATH_RE, isIconSlug, type IconKey } from "../src/core/icons/constants";

const ROOT = resolve(import.meta.dir, "..");
const ICONS_DIR = join(ROOT, "icons");
const OUT = join(ROOT, "src", "core", "icons", "builtin-assets.ts");

interface Manifest {
  schemaVersion?: unknown;
  name?: unknown;
  icons?: unknown;
}

function fail(message: string): never {
  process.stderr.write(`md-preview: ${message}\n`);
  process.exit(1);
}

function readManifest(file: string): Manifest {
  try {
    return JSON.parse(readFileSync(join(ICONS_DIR, file), "utf8")) as Manifest;
  } catch (err) {
    fail(`could not read icons/${file}: ${err instanceof Error ? err.message : String(err)}`);
  }
}

function main(): void {
  const files = readdirSync(ICONS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) => entry.name)
    .filter((name) => name !== "icon.schema.json")
    .sort((a, b) => a.localeCompare(b));

  const entries: Array<[string, string]> = [];
  for (const file of files) {
    const slug = file.slice(0, -".json".length);
    if (!isIconSlug(slug)) {
      fail(`invalid builtin icon pack file name ${file}`);
    }
    const manifest = readManifest(file);
    if (manifest.schemaVersion !== 1 || manifest.name !== slug) {
      fail(`icons/${file} must use schemaVersion 1 and name ${JSON.stringify(slug)}`);
    }
    if (typeof manifest.icons !== "object" || manifest.icons === null) {
      fail(`icons/${file} must define an icons object`);
    }
    for (const key of ICON_KEYS) {
      const value = (manifest.icons as Record<string, unknown>)[key as IconKey];
      if (value === undefined) {
        continue;
      }
      if (typeof value !== "string" || !ICON_PATH_RE.test(value)) {
        fail(`icons/${file}: ${key} must be a relative SVG path`);
      }
      const source = join(ICONS_DIR, value);
      let svg: string;
      try {
        svg = readFileSync(source, "utf8");
      } catch (err) {
        fail(
          `icons/${file}: could not read ${value}: ${err instanceof Error ? err.message : String(err)}`
        );
      }
      if (!svg.includes("<svg")) {
        fail(`icons/${file}: ${value} is not an SVG`);
      }
      entries.push([`${slug}:${key}`, svg.trim()]);
    }
  }

  const lines = [
    "// Generated by `bun run icons:assets`. Do not edit.",
    "//",
    "// Builtin SVG assets embedded for the compiled binary: `icons/` is not",
    "// available at runtime once Bun compiles the CLI.",
    "",
    "export const BUNDLED_ICON_SVGS: ReadonlyMap<string, string> = new Map<string, string>([",
    ...entries.map(([key, svg]) => `  [${JSON.stringify(key)}, ${JSON.stringify(svg)}],`),
    "]);",
    "",
  ];
  writeFileSync(OUT, lines.join("\n"), { mode: 0o644 });
  process.stdout.write(`wrote ${OUT} (${entries.length} icons)\n`);
}

main();
