/**
 * Regenerates `src/core/markdown/shiki-builtins.ts` from `@shikijs/themes`.
 *
 * Run manually after upgrading the package:
 *
 * ```sh
 * bun run scripts/gen-shiki-themes.ts
 * ```
 *
 * The output is committed; the server runtime imports the generated table and
 * never the 65 modules directly. Each entry keeps a thunk with a static
 * specifier so Bun's compiler includes the module in the binary while only
 * evaluating it when the theme is actually used.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { themeNames } from "@shikijs/themes";

interface ShikiThemeModule {
  type?: string;
  colors?: Record<string, string>;
}

const OUTPUT = join(import.meta.dir, "..", "src", "core", "markdown", "shiki-builtins.ts");

function luminance(color: string | undefined): number | null {
  if (!color) {
    return null;
  }
  const hex = color.trim().replace(/^#/, "");
  if (!/^[0-9a-fA-F]{6}$/.test(hex)) {
    return null;
  }
  const channels = [0, 2, 4].map((offset) => {
    const value = Number.parseInt(hex.slice(offset, offset + 2), 16) / 255;
    return value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2];
}

function inferKind(name: string, mod: ShikiThemeModule): "light" | "dark" {
  if (mod.type === "light" || mod.type === "dark") {
    return mod.type;
  }
  const bg = mod.colors?.["editor.background"] ?? mod.colors?.bg;
  const value = luminance(bg);
  if (value === null) {
    throw new Error(`cannot infer polarity of Shiki theme ${name}`);
  }
  return value < 0.5 ? "dark" : "light";
}

const entries: Array<{ name: string; kind: "light" | "dark" }> = [];
for (const name of themeNames) {
  const mod = (await import(`@shikijs/themes/${name}`)).default as ShikiThemeModule;
  entries.push({ name, kind: inferKind(name, mod) });
}

const lines: string[] = [];
lines.push("/**");
lines.push(" * Generated by `scripts/gen-shiki-themes.ts`; do not edit by hand.");
lines.push(" *");
lines.push(" * The thunks use static specifiers so the bundler includes each theme");
lines.push(" * module, while `load()` only runs the import when the theme is used.");
lines.push(" */");
lines.push('import type { ThemeRegistration } from "shiki/types";');
lines.push("");
lines.push('import type { BuiltinShikiThemeName } from "../themes/constants";');
lines.push("");
lines.push("export interface BuiltinShikiTheme {");
lines.push("  name: BuiltinShikiThemeName;");
lines.push('  kind: "light" | "dark";');
lines.push("  load(): Promise<ThemeRegistration>;");
lines.push("}");
lines.push("");
lines.push("export const BUILTIN_SHIKI_THEMES: readonly BuiltinShikiTheme[] = [");
for (const { name, kind } of entries) {
  lines.push(
    `  { name: ${JSON.stringify(name)}, kind: ${JSON.stringify(kind)}, load: () => import("@shikijs/themes/${name}").then((m) => m.default) },`
  );
}
lines.push("];");
lines.push("");
lines.push("export const BUILTIN_SHIKI_THEME_NAMES: ReadonlySet<string> = new Set(");
lines.push("  BUILTIN_SHIKI_THEMES.map((theme) => theme.name)");
lines.push(");");
lines.push("");

writeFileSync(OUTPUT, lines.join("\n"), "utf8");
console.log(`wrote ${OUTPUT} (${entries.length} themes)`);
